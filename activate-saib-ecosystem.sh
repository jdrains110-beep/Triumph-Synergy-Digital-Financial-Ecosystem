# =============================================================================
# PHASE 6: DEPLOYMENT
# =============================================================================

deploy_production() {
    section "PHASE 6: PRODUCTION DEPLOYMENT"
    
    log "Preparing production deployment..."
    
    # Check if secrets are configured
    if [[ -f "$WORKSPACE_ROOT/.env.production" ]]; then
        if grep -q "replace-me" "$WORKSPACE_ROOT/.env.production"; then
            error "Environment still contains placeholder values"
            error "Update .env.production before deployment"
            return 1
        fi
        success "Environment configuration verified"
    fi
    
    # Deploy to Vercel (Next.js)
    log "Deploying Next.js to Vercel..."
    if command -v vercel &> /dev/null; then
        cd "$WORKSPACE_ROOT"
        vercel deploy --prod --token="${VERCEL_TOKEN:-}" 2>&1 | tail -20 | tee -a "$LOG_FILE"
        success "Vercel deployment initiated"
    else
        warning "Vercel CLI not found. Skipping Next.js deployment."
        warning "Deploy manually: vercel deploy --prod"
    fi
    
    # Deploy to Cloudflare Workers
    log "Deploying Cloudflare Worker..."
    if command -v wrangler &> /dev/null; then
        cd "$WORKSPACE_ROOT"
        wrangler publish --env production 2>&1 | tail -20 | tee -a "$LOG_FILE"
        success "Cloudflare Worker deployment initiated"
    else
        warning "Wrangler CLI not found. Skipping Worker deployment."
        warning "Deploy manually: wrangler publish --env production"
    fi
}


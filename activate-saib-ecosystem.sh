# =============================================================================
# UTILITY FUNCTIONS
# =============================================================================

log() {
    echo -e "${BLUE}[$(date +'%Y-%m-%d %H:%M:%S')]${NC} $1" | tee -a "$LOG_FILE"
}

success() {
    echo -e "${GREEN}✅ $1${NC}" | tee -a "$LOG_FILE"
}

error() {
    echo -e "${RED}❌ $1${NC}" | tee -a "$LOG_FILE"
}

warning() {
    echo -e "${YELLOW}⚠️  $1${NC}" | tee -a "$LOG_FILE"
}

section() {
    echo -e "\n${MAGENTA}════════════════════════════════════════════${NC}" | tee -a "$LOG_FILE"
    echo -e "${MAGENTA}$1${NC}" | tee -a "$LOG_FILE"
    echo -e "${MAGENTA}════════════════════════════════════════════${NC}" | tee -a "$LOG_FILE"
}

# =============================================================================
# PHASE 1: PRE-FLIGHT CHECKS
# =============================================================================

preflight_checks() {
    section "PHASE 1: PRE-FLIGHT CHECKS"
    
    log "Checking Node.js installation..."
    if ! command -v node &> /dev/null; then
        error "Node.js not found. Please install Node.js 18+"
        exit 1
    fi
    success "Node.js $(node --version) found"
    
    log "Checking Git installation..."
    if ! command -v git &> /dev/null; then
        error "Git not found. Please install Git"
        exit 1
    fi
    success "Git found"
    
    log "Checking current branch..."
    CURRENT_BRANCH=$(cd "$WORKSPACE_ROOT" && git rev-parse --abbrev-ref HEAD)
    if [[ "$CURRENT_BRANCH" != "feat/saib-nano-sovereign-self-awareness" ]]; then
        warning "Current branch is $CURRENT_BRANCH, expected feat/saib-nano-sovereign-self-awareness"
        read -p "Continue anyway? (y/n) " -n 1 -r
        echo
        if [[ ! $REPLY =~ ^[Yy]$ ]]; then
            error "Activation cancelled"
            exit 1
        fi
    fi
    success "Branch verification passed"
    
    log "Checking required files..."
    REQUIRED_FILES=(
        "lib/saib/allodial-deed-factory.ts"
        "lib/saib/deed-witness-schema.ts"
        "lib/saib/quantum-builder.ts"
        "lib/saib/quantum-worker.ts"
        "app/api/saib/allodial/issue-deed/route.ts"
        "components/deed-certificate.tsx"
        "supabase/schema-setup.sql"
    )
    
    for file in "${REQUIRED_FILES[@]}"; do
        if [[ ! -f "$WORKSPACE_ROOT/$file" ]]; then
            error "Missing required file: $file"
            exit 1
        fi
    done
    success "All required files present"
}


    echo "  Response: $RESPONSE" | head -c 100
    
    # Test 2: Process request
    log "Test 2: Process deed request (async)"
    RESPONSE=$(curl -s -X POST \
        -H "X-SAIB-ID: SAIB-OPTIMUS-001" \
        -H "Content-Type: application/json" \
        -d '{"domain":"test.pi","deedCertificateId":"ALLODIAL-DEED-TEST"}' \
        "$DOMAIN/api/saib/quantum/process")
    echo "  Response: $RESPONSE" | head -c 100
    
    # Test 3: Admin reset (if token provided)
    if [[ ! -z "$ADMIN_TOKEN" ]]; then
        log "Test 3: Admin reset endpoint"
        RESPONSE=$(curl -s -X POST \
            -H "Authorization: Bearer $ADMIN_TOKEN" \
            "$DOMAIN/api/saib/quantum/admin/reset")
        echo "  Response: $RESPONSE" | head -c 100
    fi
    
    success "System testing completed"

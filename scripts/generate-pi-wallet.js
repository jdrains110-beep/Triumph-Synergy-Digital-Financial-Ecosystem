#!/usr/bin/env node
/**
 * Pi/Stellar wallet generator
 * ────────────────────────────────────────────────────────────────────────────
 * Generates a fresh Stellar/Pi keypair for use with the tokenization-engine
 * broadcaster. By default writes to .env.local (gitignored) — never to .env.
 *
 * Usage (run inside settlement-core which has @stellar/stellar-sdk installed):
 *   docker exec triumph-settlement-core node /tmp/generate-pi-wallet.js --testnet
 *
 * Or locally if you have the SDK installed:
 *   node scripts/generate-pi-wallet.js --testnet
 *
 * Flags:
 *   --testnet     mark output as testnet preset (default: mainnet preset)
 *   --print       print to stdout instead of writing a file
 *   --out=PATH    write env-format output to PATH (default: .env.local)
 *
 * IMPORTANT:
 *   - The SECRET key starts with "S" and CAN SIGN. Treat it like a password.
 *   - Never commit .env.local. Confirm `.env.local` is in .gitignore.
 *   - For testnet, fund the new address via Pi Browser → Pi Testnet Wallet faucet.
 *   - For mainnet, you generally do NOT generate a key here — you use your
 *     existing Pi Wallet passphrase. This script is mainly for TESTNET.
 */

const { Keypair } = require("@stellar/stellar-sdk");
const fs = require("node:fs");
const path = require("node:path");

const args = process.argv.slice(2);
const testnet = args.includes("--testnet");
const printOnly = args.includes("--print");
const outArg = args.find((a) => a.startsWith("--out="));
const outPath = outArg ? outArg.slice(6) : ".env.local";

const kp = Keypair.random();
const publicKey = kp.publicKey();
const secret = kp.secret();

const horizon = testnet
  ? "https://api.testnet.minepi.com"
  : "https://api.mainnet.minepi.com";
const passphrase = testnet ? "Pi Testnet" : "Pi Network";
const network = testnet ? "testnet" : "mainnet";
const explorer = testnet
  ? `https://blockexplorer.minepi.com/testnet/account/${publicKey}`
  : `https://blockexplorer.minepi.com/mainnet/account/${publicKey}`;

const block = `# Generated by scripts/generate-pi-wallet.js — ${new Date().toISOString()}
# Network: ${network}
# Public key (G…):  ${publicKey}
# Explorer: ${explorer}
# Fund this address before enabling broadcast.

PI_NETWORK_MODE=${network}
STELLAR_HORIZON_URL=${horizon}
STELLAR_NETWORK_PASSPHRASE=${passphrase}
STELLAR_BROADCAST_ENABLED=true
STELLAR_TREASURY_ADDRESS=${publicKey}
STELLAR_SECRET_KEY=${secret}
`;

if (printOnly) {
  process.stdout.write(block);
  process.exit(0);
}

const target = path.resolve(outPath);
fs.writeFileSync(target, block, { mode: 0o600 });

console.log(`✓ Wallet generated for ${network}`);
console.log(`  Public:    ${publicKey}`);
console.log(`  Secret:    [REDACTED — written to ${target}]`);
console.log(`  Explorer:  ${explorer}`);
console.log(`  Horizon:   ${horizon}`);
console.log("");
console.log("Next steps:");
if (testnet) {
  console.log("  1. Open Pi Browser → Pi Testnet Wallet → faucet to fund this address");
} else {
  console.log("  1. ⚠  MAINNET — only use a key you control. Funding required.");
}
console.log("  2. Verify .env.local is in .gitignore (NEVER commit the secret key)");
console.log("  3. cat .env.local >> .env   (or merge into your env source)");
console.log("  4. docker compose up -d --force-recreate settlement-core");
console.log("  5. curl http://localhost:8089/api/stellar/status   (inside container)");
console.log("  6. Re-run scripts/tokenize-hq.py to mint with real broadcasts");
